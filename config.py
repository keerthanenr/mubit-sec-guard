DEFAULT_BASE_URL = "https://api.mubit.ai/openai/v1"
DEFAULT_MODEL = "gpt-6-luna"
MAX_SNIPPET_CHARS = 1500
# Deterministic provider answers on the OpenAI-format route (the adapter is trained and tested
# against them). Mubit doesn't group tasks by temperature. The Anthropic route can't send it.
TEMPERATURE = 0
MAX_REPLY_TOKENS = 16  # Anthropic requires max_tokens; a label needs a few. Constant, so tasks don't split.
# Opus 5.5 always thinks (it can't be turned off), and thinking counts toward max_tokens.
THINKING_REPLY_TOKENS = 2048
TIMEOUT_SECONDS = 20
MAX_RETRIES = 2
DEFAULT_BUDGET_USD = 50.0


def base_url():
    return os.environ.get("MUBIT_BASE_URL") or DEFAULT_BASE_URL


def gemini_route():
    return "/gemini" in base_url()


def anthropic_route():
    """Native Anthropic Messages on Mubit's documented /anthropic address (no /v1)."""
    return base_url().rstrip("/").endswith("/anthropic")


def model():
    return os.environ.get("MUBIT_MODEL") or DEFAULT_MODEL


def always_thinks():
    return model().startswith("claude-opus-5")


def reply_tokens():
    return THINKING_REPLY_TOKENS if always_thinks() else MAX_REPLY_TOKENS


def anthropic_options():
    """Fixed per-model request options (constant per model, so tasks don't split)."""
    # Low effort keeps Opus's thinking short: it is choosing one label, not reasoning at length.
    return {"output_config": {"effort": "low"}} if always_thinks() else {}


def api_key():
    return os.environ.get("MUBIT_API_KEY", "")


def budget_usd():
    return float(os.environ.get("GUARD_BUDGET_USD") or DEFAULT_BUDGET_USD)


def offline():
    return os.environ.get("GUARD_OFFLINE") == "1"


def disabled():
    return os.environ.get("GUARD_DISABLED") == "1"


def scope_dir():
    """The hook only scans files under this folder (GUARD_SCOPE_DIR, default
    demo-app/ in the project), so it never scans this project's own scripts."""
    scope = Path(os.environ.get("GUARD_SCOPE_DIR") or "demo-app")
    project = Path(os.environ.get("CLAUDE_PROJECT_DIR") or ROOT)
    return (scope if scope.is_absolute() else project / scope).resolve()


def state_dir():
    """Where findings.jsonl, spend.json and .guard_state.json live (tests override this)."""
    return Path(os.environ.get("GUARD_STATE_DIR") or ROOT)

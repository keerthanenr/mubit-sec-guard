"""Env loading, lanes (instruction + labels + fix hints) and shared settings."""
import os
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def load_env(path=ROOT / ".env"):
    """Minimal .env loader. Real environment variables win over the file."""
    if not path.exists():
        return
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


load_env()


@dataclass(frozen=True)
class Lane:
    name: str
    # ONE constant per lane. Never template or edit it: Mubit groups calls into a
    # task only when the system prompt is byte-identical, so each lane's
    # instruction is what gives it its own task and its own adapter.
    instruction: str
    labels: tuple
    fix_hints: dict
    # Routing: a file goes to this lane if its suffix is in `suffixes` and either
    # `modules` is empty or the code imports one of them. `always_suffixes`
    # route without an import check (e.g. notebooks).
    suffixes: tuple = ()
    modules: tuple = ()
    always_suffixes: tuple = ()
    # Extra routing for config files: any of these in the path, or all of these in the text.
    path_markers: tuple = ()
    content_markers: tuple = ()


